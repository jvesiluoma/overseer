#!/usr/bin/env python3
"""Embeds WebClient/* into Sources/OverscreenServer/Generated/WebAssets.swift.

Run after editing the web client: python3 -I scripts/embed-webclient.py
The test suite fails if the generated file is out of date.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "WebClient"
OUT = ROOT / "Sources" / "OverscreenServer" / "Generated" / "WebAssets.swift"
TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
}


def render() -> str:
    lines = [
        "// GENERATED by scripts/embed-webclient.py from WebClient/. Do not edit.",
        "",
        "enum WebAssets {",
        "    struct Asset {",
        "        let contentType: String",
        "        let body: String",
        "    }",
        "",
        "    static let files: [String: Asset] = [",
    ]
    for path in sorted(SRC.iterdir()):
        if path.suffix not in TYPES:
            continue
        text = path.read_text(encoding="utf-8")
        if '"""#' in text or "\\#(" in text:
            sys.exit(f"{path.name}: contains a sequence that breaks Swift raw strings")
        lines.append(f'        "{path.name}": Asset(contentType: "{TYPES[path.suffix]}", body: #"""')
        lines.append(text.rstrip("\n"))
        lines.append('"""#),')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
